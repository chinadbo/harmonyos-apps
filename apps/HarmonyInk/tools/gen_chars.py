def resample(points, step=2.2):
    """按弧长等距重采样，输出 0.1 精度坐标。"""
    if len(points) < 2:
        return points
    total = 0.0
    for i in range(len(points) - 1):
        total += math.hypot(points[i + 1][0] - points[i][0], points[i + 1][1] - points[i][1])
    if total < 0.001:
        return [points[0]]
    count = max(2, int(total / step) + 1)
    result = []
    for k in range(count + 1):
        target = total * k / count
        walked = 0.0
        for i in range(len(points) - 1):
            seg = math.hypot(points[i + 1][0] - points[i][0], points[i + 1][1] - points[i][1])
            if walked + seg >= target or i == len(points) - 2:
                t = 0.0 if seg < 1e-6 else (target - walked) / seg
                x = points[i][0] + (points[i + 1][0] - points[i][0]) * t
                y = points[i][1] + (points[i + 1][1] - points[i][1]) * t
                result.append([round(x, 1), round(y, 1)])
                break
            walked += seg
    # 去重
    cleaned = []
    for p in result:
        if not cleaned or abs(cleaned[-1][0] - p[0]) > 0.05 or abs(cleaned[-1][1] - p[1]) > 0.05:
            cleaned.append(p)
    return cleaned


def start_direction(points):
    if len(points) < 2:
        return 0.0
    total = 0.0
    segs = []
    for i in range(len(points) - 1):
        seg = math.hypot(points[i + 1][0] - points[i][0], points[i + 1][1] - points[i][1])
        segs.append(seg)
        total += seg
    target = total * 0.18
    walked = 0.0
    end = points[-1]
    for i, seg in enumerate(segs):
        if walked + seg >= target:
            t = 0.0 if seg < 1e-6 else (target - walked) / seg
            end = (points[i][0] + (points[i + 1][0] - points[i][0]) * t,
                   points[i][1] + (points[i + 1][1] - points[i][1]) * t)
            break
        walked += seg
    return round(math.degrees(math.atan2(end[1] - points[0][1], end[0] - points[0][0])), 1)


def build():
    seen = set()
    output = []
    for char, pinyin, grade, raw_strokes in CHARS:
        if char in seen:
            raise ValueError(f"重复汉字: {char}")
        seen.add(char)
        strokes = []
        for idx, (stroke_type, control_points) in enumerate(raw_strokes):
            pts = resample(control_points)
            if len(pts) < 2:
                raise ValueError(f"{char} 第{idx + 1}笔采样点不足")
            strokes.append({
                "index": idx + 1,
                "type": stroke_type,
                "points": [{"x": p[0], "y": p[1]} for p in pts],
                "startDir": start_direction(pts),
            })
        output.append({
            "char": char,
            "pinyin": pinyin,
            "grade": grade,
            "strokes": strokes,
        })
    return output


def main():
    data = build()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target = os.path.join(root, "entry", "src", "main", "resources", "rawfile", "chars.json")
